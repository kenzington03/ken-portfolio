export function getCandidateImageUrls(folder) {
  if (!folder) return [];
  return IMAGE_CANDIDATES.map((file) => `/assets/projects/${folder}/${file}`);
}

export function getGalleryImageUrls(folder) {
  if (!folder || !GALLERY_MANIFEST[folder]) return [];
  return GALLERY_MANIFEST[folder].map((file) => `/assets/projects/${folder}/${file}`);
}

/** Candidate filenames first, then known gallery paths (deduped, order preserved) */
export function getAllImageUrlsToTry(folder) {
  const seen = new Set();
  const urls = [];
  for (const url of [...getCandidateImageUrls(folder), ...getGalleryImageUrls(folder)]) {
    if (!seen.has(url)) {
      seen.add(url);
      urls.push(url);
    }
  }
  return urls;
}

export function probeProjectImages(folder) {
  const urls = getAllImageUrlsToTry(folder);
  if (urls.length === 0) return Promise.resolve([]);

  return new Promise((resolve) => {
    const ok = new Array(urls.length).fill(false);
    let remaining = urls.length;

    const finishOne = (index, success) => {
      ok[index] = success;
      remaining -= 1;
      if (remaining === 0) {
        resolve(urls.filter((_, i) => ok[i]));
      }
    };

    urls.forEach((url, index) => {
      const img = new Image();
      img.onload = () => finishOne(index, true);
      img.onerror = () => finishOne(index, false);
      img.src = url;
    });
  });
}
