export function getSectionManifestImages(folder, slug) {
  const files = SECTION_IMAGE_MANIFEST[folder]?.[slug];
  if (!files?.length) return [];
  return files.map((file) => {
    const slugPath = slug.split('/').map((part) => encodeURIComponent(part)).join('/');
    return `/assets/projects/${folder}/${slugPath}/${file}`;
  });
}
